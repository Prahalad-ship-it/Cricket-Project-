import tempfile
import unittest
from pathlib import Path
from types import SimpleNamespace
from typing import Any
from unittest.mock import MagicMock, call, patch

import numpy as np

from cricket_coach.data_contract import load_phase_payload, save_phase_payload
from cricket_coach.phase2_tracking.pose_3d import Pose3DProcessor
from cricket_coach.phase6_app import dashboard


class _FakeCapture:
    def __init__(self) -> None:
        self.frames = [np.zeros((4, 4, 3), dtype=np.uint8) for _ in range(3)]

    def isOpened(self) -> bool:
        return True

    def get(self, property_id: int) -> float:
        return 30.0

    def read(self) -> tuple[bool, np.ndarray | None]:
        if not self.frames:
            return False, None
        return True, self.frames.pop(0)

    def release(self) -> None:
        pass


class _FakePoseModel:
    def __init__(self) -> None:
        self.xy = np.arange(34, dtype=np.float32).reshape(1, 17, 2)

    def __call__(self, frame: np.ndarray, verbose: bool = False) -> list[Any]:
        boxes = SimpleNamespace(xyxy=np.array([[0, 0, 20, 20]], dtype=np.float32))
        keypoints = SimpleNamespace(
            xy=self.xy,
            conf=np.ones((1, 17), dtype=np.float32),
        )
        return [SimpleNamespace(boxes=boxes, keypoints=keypoints)]


class _FailingLifter:
    def lift_frame(self, frame: np.ndarray) -> np.ndarray:
        raise RuntimeError("inference failed")


class PoseFallbackTests(unittest.TestCase):
    def _run_processor(self, processor: Pose3DProcessor, root: Path) -> tuple[dict, dict]:
        metadata_path = root / "delivery_test_data.json"
        save_phase_payload(metadata_path, {"delivery_id": "delivery_test"})
        with patch(
            "cricket_coach.phase2_tracking.pose_3d.cv2.VideoCapture",
            return_value=_FakeCapture(),
        ):
            metadata, arrays = processor.process("unused.mp4", metadata_path)
        saved, _ = load_phase_payload(metadata_path)
        self.assertEqual(saved["phase_errors"], metadata["phase_errors"])
        return metadata, arrays

    def test_inference_exception_is_recorded_and_uses_2d_landmarks(self) -> None:
        pose_model = _FakePoseModel()
        processor = Pose3DProcessor(pose_model=pose_model, lifter=_FailingLifter())
        with tempfile.TemporaryDirectory() as directory:
            metadata, arrays = self._run_processor(processor, Path(directory))

        self.assertEqual(
            metadata["phase_errors"]["tracking_pose"],
            "RuntimeError: inference failed",
        )
        self.assertEqual(metadata["pose_status"], "external_lifter_error_2d_fallback")
        self.assertEqual(metadata["pose_3d_valid_frame_count"], 3)
        self.assertTrue(arrays["pose_3d_fallback_frames"].all())
        np.testing.assert_array_equal(
            arrays["poses_3d"][..., :2],
            np.repeat(pose_model.xy, 3, axis=0),
        )

    def test_lifter_initialization_exception_is_recorded(self) -> None:
        with patch(
            "cricket_coach.phase2_tracking.pose_3d.MediaPipeWorldPoseLifter",
            side_effect=RuntimeError("initialization failed"),
        ):
            processor = Pose3DProcessor(pose_model=_FakePoseModel())
        with tempfile.TemporaryDirectory() as directory:
            metadata, arrays = self._run_processor(processor, Path(directory))

        self.assertEqual(
            metadata["phase_errors"]["tracking_pose"],
            "RuntimeError: initialization failed",
        )
        self.assertEqual(metadata["pose_status"], "mediapipe_error_2d_fallback")
        self.assertEqual(metadata["pose_3d_valid_frame_count"], 3)
        self.assertTrue(arrays["pose_3d_fallback_frames"].all())


class DashboardDiagnosticsTests(unittest.TestCase):
    def test_pipeline_health_opens_when_biomechanics_are_unavailable(self) -> None:
        st = MagicMock()
        metadata = {
            "phase_status": {"tracking_pose": "mediapipe_error_2d_fallback"},
            "pose_3d_valid_frame_count": 3,
            "phase_errors": {"tracking_pose": "RuntimeError: inference failed"},
            "coach": {"generated_by": "meta/muse-glimmer-30b"},
            "biomechanics": {"front_knee_angle_deg": {"min": None}},
        }

        dashboard._render_pipeline_health(st, metadata, {})

        st.expander.assert_called_once_with(
            "Pipeline Health & Debug Status",
            expanded=True,
        )
        st.json.assert_any_call(metadata["phase_status"])
        st.json.assert_any_call(metadata["phase_errors"])
        self.assertIn(
            call("Coach generated by", "meta/muse-glimmer-30b"),
            st.write.call_args_list,
        )

    def test_pipeline_health_opens_when_phase_errors_are_present(self) -> None:
        st = MagicMock()
        metadata = {
            "phase_status": {"tracking_pose": "mediapipe_world_landmarks"},
            "phase_errors": {"tracking_pose": "fallback was used"},
            "biomechanics": {
                "front_knee_angle_deg": {"min": 150.0},
                "bowling_elbow_angle_deg": {"min": 140.0},
                "lateral_trunk_tilt_deg": {"max": 25.0},
                "bowling_elbow_extension_deg": {"max": 10.0},
            },
        }

        dashboard._render_pipeline_health(st, metadata, {})

        st.expander.assert_called_once_with(
            "Pipeline Health & Debug Status",
            expanded=True,
        )

    def test_fallback_frame_uses_2d_preview(self) -> None:
        st = MagicMock()
        arrays = {
            "poses_3d": np.ones((1, 17, 4), dtype=np.float32),
            "poses_2d": np.ones((1, 17, 3), dtype=np.float32),
            "pose_3d_fallback_frames": np.array([True]),
        }
        with patch.object(dashboard, "_render_2d_pose") as render_2d, patch.object(
            dashboard, "_render_3d_pose"
        ) as render_3d:
            dashboard._render_skeleton(st, arrays)

        self.assertTrue(render_2d.called)
        self.assertFalse(render_3d.called)


if __name__ == "__main__":
    unittest.main()
